def card_resources(card_number: str) -> list[dict]:
    resources = RESOURCE_MAP.get(card_number, {})
    return [
        {"key": key, "label": RESOURCE_LABELS.get(key, key), "count": int(count)}
        for key, count in resources.items() if int(count) > 0
    ]


def card_resource_note(card_number: str, subgroup: str) -> str:
    if card_number in RESOURCE_MAP:
        return "击破此部位可获得"
    if subgroup.endswith(" / BP"):
        return "无直接资源（特殊 BP）"
    return ""
